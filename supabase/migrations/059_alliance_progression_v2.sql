-- -----------------------------------------------------------------------------
-- 2) DURABLE XP EVENTS + MATERIALIZED PROGRESSION STATE
-- -----------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.alliance_xp_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  alliance_id bigint NOT NULL
    REFERENCES public.alliances(id) ON DELETE CASCADE,
  source_type text NOT NULL
    CHECK (
      source_type IN (
        'mission_week',
        'war_battle_win',
        'war_win',
        'territory_claim'
      )
    ),
  source_key text NOT NULL,
  xp_amount bigint NOT NULL
    CHECK (xp_amount > 0),
  occurred_at timestamptz NOT NULL,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb
    CHECK (jsonb_typeof(metadata) = 'object'),
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  UNIQUE (alliance_id, source_type, source_key)
);

CREATE INDEX IF NOT EXISTS idx_alliance_xp_events_alliance_time
  ON public.alliance_xp_events(
    alliance_id,
    occurred_at,
    id
  );

CREATE TABLE IF NOT EXISTS public.alliance_progression (
  alliance_id bigint PRIMARY KEY
    REFERENCES public.alliances(id) ON DELETE CASCADE,
  total_xp bigint NOT NULL DEFAULT 0
    CHECK (total_xp >= 0),
  level integer NOT NULL DEFAULT 1
    CHECK (level BETWEEN 1 AND 10),
  updated_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

CREATE TABLE IF NOT EXISTS public.alliance_level_milestones (
  alliance_id bigint NOT NULL
    REFERENCES public.alliances(id) ON DELETE CASCADE,
  level integer NOT NULL
    REFERENCES public.game_alliance_levels(level) ON DELETE RESTRICT,
  reached_at timestamptz NOT NULL,
  total_xp_at_reach bigint NOT NULL
    CHECK (total_xp_at_reach >= 0),
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  PRIMARY KEY (alliance_id, level)
);

CREATE TABLE IF NOT EXISTS public.player_alliance_level_reward_claims (
  player_id bigint NOT NULL
    REFERENCES public.players(id) ON DELETE CASCADE,
  alliance_id bigint NOT NULL
