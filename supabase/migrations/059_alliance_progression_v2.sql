CREATE OR REPLACE FUNCTION public.nexora_track_alliance_mission_xp()
RETURNS trigger
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public, pg_temp
AS $function$
BEGIN
  PERFORM public.nexora_add_alliance_xp_event(
    NEW.alliance_id,
    'mission_week',
    NEW.week_start::text,
    250,
    NEW.claimed_at,
    jsonb_build_object('weekStart', NEW.week_start)
  );
  RETURN NEW;
END;
$function$;

