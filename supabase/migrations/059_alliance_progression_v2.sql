-- -----------------------------------------------------------------------------
-- 6) READ-ONLY SNAPSHOT
-- -----------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.nexora_alliance_progression_snapshot(
  p_player_id bigint
)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY INVOKER
SET search_path = public, pg_temp
AS $function$
DECLARE
  v_member public.alliance_members%ROWTYPE;
  v_alliance public.alliances%ROWTYPE;
  v_progress public.alliance_progression%ROWTYPE;
  v_current public.game_alliance_levels%ROWTYPE;
  v_next public.game_alliance_levels%ROWTYPE;
  v_levels jsonb := '[]'::jsonb;
  v_xp_sources jsonb := '{}'::jsonb;
  v_recent_xp jsonb := '[]'::jsonb;
BEGIN
  IF p_player_id IS NULL OR p_player_id <= 0 THEN
    RETURN jsonb_build_object(
      'success', false,
      'code', 'INVALID_PLAYER',
      'message', 'Geçersiz oyuncu.'
    );
  END IF;

  SELECT am.*
    INTO v_member
    FROM public.alliance_members am
   WHERE am.player_id = p_player_id
   LIMIT 1;

  IF v_member.id IS NULL THEN
    RETURN jsonb_build_object(
      'success', true,
      'inAlliance', false,
      'levels', '[]'::jsonb,
      'recentXp', '[]'::jsonb
    );
  END IF;

  SELECT a.*
    INTO v_alliance
    FROM public.alliances a
   WHERE a.id = v_member.alliance_id;

  SELECT ap.*
    INTO v_progress
    FROM public.alliance_progression ap
   WHERE ap.alliance_id = v_member.alliance_id;

  IF v_progress.alliance_id IS NULL THEN
    v_progress.alliance_id := v_member.alliance_id;
    v_progress.total_xp := 0;
    v_progress.level := 1;
  END IF;

  SELECT l.*
    INTO v_current
    FROM public.game_alliance_levels l
   WHERE l.level = v_progress.level;

  SELECT l.*
    INTO v_next
    FROM public.game_alliance_levels l
   WHERE l.level = v_progress.level + 1;

  SELECT COALESCE(
           jsonb_object_agg(x.source_type, x.xp),
           '{}'::jsonb
         )
    INTO v_xp_sources
    FROM (
      SELECT
        e.source_type,
        SUM(e.xp_amount)::bigint AS xp
      FROM public.alliance_xp_events e
      WHERE e.alliance_id = v_member.alliance_id
      GROUP BY e.source_type
    ) x;

  SELECT COALESCE(
           jsonb_agg(
             jsonb_build_object(
               'level', l.level,
               'title', l.title,
               'xpRequired', l.xp_required,
               'reward', l.reward,
               'reached', m.level IS NOT NULL,
               'reachedAt', m.reached_at,
               'eligible',
                 m.level IS NOT NULL
                 AND v_member.joined_at <= m.reached_at,
               'claimed', claim.level IS NOT NULL,
               'claimedAt', claim.claimed_at,
               'creditedReward',
                 COALESCE(claim.reward, '{}'::jsonb),
               'claimable',
                 m.level IS NOT NULL
                 AND v_member.joined_at <= m.reached_at
                 AND claim.level IS NULL
                 AND l.level >= 2
             )
             ORDER BY l.level
           ),
           '[]'::jsonb
         )
    INTO v_levels
    FROM public.game_alliance_levels l
    LEFT JOIN public.alliance_level_milestones m
      ON m.alliance_id = v_member.alliance_id
     AND m.level = l.level
    LEFT JOIN public.player_alliance_level_reward_claims claim
      ON claim.player_id = p_player_id
     AND claim.alliance_id = v_member.alliance_id
     AND claim.level = l.level;

  SELECT COALESCE(
           jsonb_agg(
             jsonb_build_object(
               'sourceType', x.source_type,
               'xp', x.xp_amount,
               'occurredAt', x.occurred_at,
               'metadata', x.metadata
             )
             ORDER BY x.occurred_at DESC, x.id DESC
           ),
           '[]'::jsonb
         )
    INTO v_recent_xp
    FROM (
      SELECT e.*
        FROM public.alliance_xp_events e
       WHERE e.alliance_id = v_member.alliance_id
       ORDER BY e.occurred_at DESC, e.id DESC
       LIMIT 10
    ) x;

  RETURN jsonb_build_object(
    'success', true,
    'inAlliance', true,
    'alliance', jsonb_build_object(
      'id', v_alliance.id,
      'name', v_alliance.name,
      'tag', v_alliance.tag
    ),
    'member', jsonb_build_object(
      'playerId', v_member.player_id,
      'joinedAt', v_member.joined_at,
      'role',
        CASE
          WHEN v_member.role = 'leader' THEN 'leader'
          WHEN v_member.role_v2 = 'officer' THEN 'officer'
          ELSE 'member'
        END
    ),
    'progression', jsonb_build_object(
      'level', v_progress.level,
      'title', COALESCE(v_current.title, 'Kuruluş'),
      'totalXp', v_progress.total_xp,
      'currentLevelXp', COALESCE(v_current.xp_required, 0),
      'nextLevel', v_next.level,
      'nextTitle', v_next.title,
      'nextLevelXp', v_next.xp_required,
      'xpIntoLevel',
        GREATEST(
          0,
          v_progress.total_xp - COALESCE(v_current.xp_required, 0)
        ),
      'xpNeededForNext',
        CASE
          WHEN v_next.level IS NULL THEN 0
          ELSE GREATEST(
            0,
            v_next.xp_required - v_progress.total_xp
          )
        END,
      'maxLevel', v_next.level IS NULL
    ),
    'xpSources', v_xp_sources,
    'levels', v_levels,
    'recentXp', v_recent_xp
  );
END;
$function$;

-- -----------------------------------------------------------------------------
-- 7) MILESTONE REWARD CLAIM
-- -----------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.nexora_claim_alliance_level_reward(
  p_player_id bigint,
  p_level integer
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public, pg_temp
AS $function$
DECLARE
  v_member public.alliance_members%ROWTYPE;
  v_milestone public.alliance_level_milestones%ROWTYPE;
  v_level public.game_alliance_levels%ROWTYPE;
  v_city public.cities%ROWTYPE;
  v_existing jsonb;
  v_configured jsonb;
  v_credited jsonb;
  v_credit_metal bigint := 0;
  v_credit_energy bigint := 0;
  v_credit_water bigint := 0;
  v_credit_crystal bigint := 0;
BEGIN
  IF p_player_id IS NULL
     OR p_player_id <= 0
     OR p_level IS NULL
     OR p_level < 2
     OR p_level > 10 THEN
    RETURN jsonb_build_object(
      'success', false,
      'code', 'INVALID_INPUT',
      'message', 'Geçersiz ittifak seviye ödülü isteği.'
    );
  END IF;

  PERFORM p.id
    FROM public.players p
   WHERE p.id = p_player_id
   FOR UPDATE;

  IF NOT FOUND THEN
    RETURN jsonb_build_object(
      'success', false,
      'code', 'PLAYER_NOT_FOUND',
      'message', 'Oyuncu bulunamadı.'
    );
  END IF;

  SELECT am.*
    INTO v_member
    FROM public.alliance_members am
   WHERE am.player_id = p_player_id
   FOR UPDATE;

  IF v_member.id IS NULL THEN
    RETURN jsonb_build_object(
      'success', false,
      'code', 'NOT_IN_ALLIANCE',
      'message', 'Bir ittifaka üye değilsin.'
    );
  END IF;

  SELECT m.*
    INTO v_milestone
    FROM public.alliance_level_milestones m
   WHERE m.alliance_id = v_member.alliance_id
     AND m.level = p_level;

  IF v_milestone.alliance_id IS NULL THEN
    RETURN jsonb_build_object(
      'success', false,
      'code', 'LEVEL_NOT_REACHED',
      'message', 'İttifak bu seviyeye henüz ulaşmadı.'
    );
  END IF;

  IF v_member.joined_at > v_milestone.reached_at THEN
    RETURN jsonb_build_object(
      'success', false,
      'code', 'NOT_ELIGIBLE',
      'message', 'Bu seviye kazanıldığında ittifak üyesi değildin.'
    );
  END IF;

  SELECT l.*
    INTO v_level
    FROM public.game_alliance_levels l
   WHERE l.level = p_level;

  IF v_level.level IS NULL THEN
    RETURN jsonb_build_object(
      'success', false,
      'code', 'LEVEL_NOT_FOUND',
      'message', 'İttifak seviyesi bulunamadı.'
    );
  END IF;

  SELECT c.reward
    INTO v_existing
    FROM public.player_alliance_level_reward_claims c
   WHERE c.player_id = p_player_id
     AND c.alliance_id = v_member.alliance_id
     AND c.level = p_level
   LIMIT 1;

  IF FOUND THEN
    RETURN jsonb_build_object(
      'success', true,
      'alreadyClaimed', true,
      'message', 'Bu ittifak seviye ödülünü zaten aldın.',
      'creditedReward', COALESCE(v_existing, '{}'::jsonb),
      'snapshot',
        public.nexora_alliance_progression_snapshot(p_player_id)
    );
  END IF;

  v_configured := v_level.reward;

  IF v_configured IS NULL
     OR jsonb_typeof(v_configured) IS DISTINCT FROM 'object'
     OR EXISTS (
       SELECT 1
         FROM jsonb_each_text(v_configured) r(key, value)
        WHERE key NOT IN ('metal','energy','water','crystal')
           OR value !~ '^[0-9]+$'
           OR char_length(value) > 12
     ) THEN
    RETURN jsonb_build_object(
      'success', false,
      'code', 'ALLIANCE_LEVEL_REWARD_INVALID',
      'message', 'İttifak seviye ödülü yapılandırması geçersiz.'
    );
  END IF;

  SELECT *
    INTO v_city
    FROM public.cities c
   WHERE c.player_id = p_player_id
   ORDER BY c.id
   LIMIT 1
   FOR UPDATE;

  IF v_city.id IS NULL THEN
    RETURN jsonb_build_object(
      'success', false,
      'code', 'CITY_NOT_FOUND',
      'message', 'Şehir bulunamadı.'
    );
  END IF;

  v_credit_metal :=
    LEAST(
      COALESCE((v_configured->>'metal')::bigint, 0),
      GREATEST(
        COALESCE(v_city.metal_capacity, 0) - COALESCE(v_city.metal, 0),
        0
      )
    );

  v_credit_energy :=
    LEAST(
      COALESCE((v_configured->>'energy')::bigint, 0),
      GREATEST(
        COALESCE(v_city.energy_capacity, 0) - COALESCE(v_city.energy, 0),
        0
      )
    );

  v_credit_water :=
    LEAST(
      COALESCE((v_configured->>'water')::bigint, 0),
      GREATEST(
        COALESCE(v_city.water_capacity, 0) - COALESCE(v_city.water, 0),
        0
      )
    );

  v_credit_crystal :=
    LEAST(
      COALESCE((v_configured->>'crystal')::bigint, 0),
      GREATEST(
        COALESCE(v_city.crystal_capacity, 0) - COALESCE(v_city.crystal, 0),
        0
      )
    );

  v_credited := jsonb_build_object(
    'metal', v_credit_metal,
    'energy', v_credit_energy,
    'water', v_credit_water,
    'crystal', v_credit_crystal
  );

  INSERT INTO public.player_alliance_level_reward_claims(
    player_id,
    alliance_id,
    level,
    configured_reward,
    reward,
    claimed_at
  )
  VALUES(
    p_player_id,
    v_member.alliance_id,
    p_level,
    v_configured,
    v_credited,
    clock_timestamp()
  )
  ON CONFLICT (player_id, alliance_id, level) DO NOTHING;

  IF NOT FOUND THEN
    SELECT c.reward
      INTO v_existing
      FROM public.player_alliance_level_reward_claims c
     WHERE c.player_id = p_player_id
       AND c.alliance_id = v_member.alliance_id
       AND c.level = p_level
     LIMIT 1;

    RETURN jsonb_build_object(
      'success', true,
      'alreadyClaimed', true,
      'message', 'Bu ittifak seviye ödülünü zaten aldın.',
      'creditedReward', COALESCE(v_existing, '{}'::jsonb),
      'snapshot',
        public.nexora_alliance_progression_snapshot(p_player_id)
    );
  END IF;

  UPDATE public.cities
     SET metal = COALESCE(metal, 0) + v_credit_metal,
         energy = COALESCE(energy, 0) + v_credit_energy,
         water = COALESCE(water, 0) + v_credit_water,
         crystal = COALESCE(crystal, 0) + v_credit_crystal,
         updated_at = clock_timestamp()
   WHERE id = v_city.id;

  INSERT INTO public.alliance_activity(
    alliance_id,
    event_type,
    actor_player_id,
    metadata,
    created_at
  )
  VALUES(
    v_member.alliance_id,
    'alliance_level_reward_claimed',
    p_player_id,
    jsonb_build_object(
      'level', p_level,
      'reward', v_credited
    ),
    clock_timestamp()
  );

  RETURN jsonb_build_object(
    'success', true,
    'alreadyClaimed', false,
    'message', 'İttifak seviye ödülü alındı.',
    'configuredReward', v_configured,
    'creditedReward', v_credited,
    'snapshot',
      public.nexora_alliance_progression_snapshot(p_player_id)
  );
END;
