-- -----------------------------------------------------------------------------
-- 3) PROGRESSION REBUILD
-- -----------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.nexora_rebuild_alliance_progression(
  p_alliance_id bigint
)
RETURNS void
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public, pg_temp
AS $function$
DECLARE
  v_total_xp bigint := 0;
  v_level integer := 1;
  v_level_row record;
  v_reached_at timestamptz;
  v_xp_at_reach bigint;
BEGIN
  IF p_alliance_id IS NULL OR p_alliance_id <= 0 THEN
    RETURN;
  END IF;

  IF NOT EXISTS (
    SELECT 1
      FROM public.alliances a
     WHERE a.id = p_alliance_id
  ) THEN
    RETURN;
  END IF;

  SELECT COALESCE(SUM(e.xp_amount), 0)::bigint
    INTO v_total_xp
    FROM public.alliance_xp_events e
   WHERE e.alliance_id = p_alliance_id;

  SELECT COALESCE(MAX(l.level), 1)
    INTO v_level
    FROM public.game_alliance_levels l
   WHERE l.xp_required <= v_total_xp;

  INSERT INTO public.alliance_progression(
    alliance_id,
    total_xp,
    level,
    updated_at
  )
  VALUES(
    p_alliance_id,
    v_total_xp,
    v_level,
    clock_timestamp()
  )
  ON CONFLICT (alliance_id) DO UPDATE SET
    total_xp = EXCLUDED.total_xp,
    level = EXCLUDED.level,
    updated_at = EXCLUDED.updated_at;

  FOR v_level_row IN
    SELECT l.level, l.xp_required
      FROM public.game_alliance_levels l
     WHERE l.level >= 2
       AND l.xp_required <= v_total_xp
     ORDER BY l.level
  LOOP
    SELECT x.occurred_at, x.running_xp
      INTO v_reached_at, v_xp_at_reach
      FROM (
        SELECT
          e.occurred_at,
          e.id,
          SUM(e.xp_amount) OVER (
            ORDER BY e.occurred_at, e.id
            ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
          )::bigint AS running_xp
        FROM public.alliance_xp_events e
        WHERE e.alliance_id = p_alliance_id
      ) x
     WHERE x.running_xp >= v_level_row.xp_required
     ORDER BY x.occurred_at, x.id
     LIMIT 1;

    IF v_reached_at IS NOT NULL THEN
      INSERT INTO public.alliance_level_milestones(
        alliance_id,
        level,
        reached_at,
        total_xp_at_reach,
        created_at
      )
      VALUES(
        p_alliance_id,
        v_level_row.level,
        v_reached_at,
        v_xp_at_reach,
        clock_timestamp()
      )
      ON CONFLICT (alliance_id, level) DO UPDATE SET
        reached_at = EXCLUDED.reached_at,
        total_xp_at_reach = EXCLUDED.total_xp_at_reach;
    END IF;
  END LOOP;
END;
$function$;

CREATE OR REPLACE FUNCTION public.nexora_add_alliance_xp_event(
  p_alliance_id bigint,
  p_source_type text,
  p_source_key text,
  p_xp_amount bigint,
  p_occurred_at timestamptz,
  p_metadata jsonb DEFAULT '{}'::jsonb
)
RETURNS boolean
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public, pg_temp
AS $function$
DECLARE
  v_inserted boolean := false;
BEGIN
  IF p_alliance_id IS NULL
     OR p_alliance_id <= 0
     OR p_source_type IS NULL
     OR p_source_type NOT IN (
       'mission_week',
       'war_battle_win',
       'war_win',
       'territory_claim'
     )
     OR p_source_key IS NULL
     OR btrim(p_source_key) = ''
     OR p_xp_amount IS NULL
     OR p_xp_amount <= 0
     OR p_occurred_at IS NULL
     OR p_metadata IS NULL
     OR jsonb_typeof(p_metadata) IS DISTINCT FROM 'object' THEN
    RETURN false;
  END IF;

  INSERT INTO public.alliance_xp_events(
    alliance_id,
    source_type,
    source_key,
    xp_amount,
    occurred_at,
    metadata,
    created_at
  )
  VALUES(
    p_alliance_id,
    p_source_type,
    p_source_key,
    p_xp_amount,
    p_occurred_at,
    p_metadata,
    clock_timestamp()
  )
  ON CONFLICT (alliance_id, source_type, source_key) DO NOTHING;

  v_inserted := FOUND;

  IF v_inserted THEN
    PERFORM public.nexora_rebuild_alliance_progression(p_alliance_id);
  END IF;

  RETURN v_inserted;
END;
$function$;

-- -----------------------------------------------------------------------------
-- 4) BACKFILL EXISTING AUTHORITATIVE HISTORY
-- -----------------------------------------------------------------------------

-- Weekly alliance mission completion: one XP event per alliance/week, regardless
-- of how many members claimed the shared chest.
INSERT INTO public.alliance_xp_events(
  alliance_id,
  source_type,
  source_key,
  xp_amount,
  occurred_at,
  metadata
)
SELECT
  c.alliance_id,
  'mission_week',
  c.week_start::text,
  250,
  MIN(c.claimed_at),
  jsonb_build_object('weekStart', c.week_start)
FROM public.player_alliance_mission_chest_claims c
GROUP BY c.alliance_id, c.week_start
ON CONFLICT (alliance_id, source_type, source_key) DO NOTHING;

-- Won war battle/round.
INSERT INTO public.alliance_xp_events(
  alliance_id,
  source_type,
  source_key,
  xp_amount,
  occurred_at,
  metadata
)
SELECT
  b.winner_alliance_id,
  'war_battle_win',
  b.id::text,
  40,
  b.battle_at,
  jsonb_build_object(
    'warId', b.war_id,
    'battleId', b.id,
    'points', b.points
  )
FROM public.alliance_war_battles b
WHERE b.winner_alliance_id IS NOT NULL
ON CONFLICT (alliance_id, source_type, source_key) DO NOTHING;

-- Finished alliance war victory.
INSERT INTO public.alliance_xp_events(
  alliance_id,
  source_type,
  source_key,
  xp_amount,
  occurred_at,
  metadata
)
SELECT
  w.winner_alliance_id,
  'war_win',
  w.id::text,
  150,
  COALESCE(w.finished_at, w.ends_at, w.started_at, w.created_at),
  jsonb_build_object(
    'warId', w.id,
    'challengerScore', w.challenger_score,
    'targetScore', w.target_score
  )
FROM public.alliance_wars w
WHERE w.status = 'finished'
  AND w.winner_alliance_id IS NOT NULL
ON CONFLICT (alliance_id, source_type, source_key) DO NOTHING;

-- Territory claims are stored as immutable alliance activity events.
INSERT INTO public.alliance_xp_events(
  alliance_id,
  source_type,
  source_key,
  xp_amount,
  occurred_at,
  metadata
)
SELECT
  aa.alliance_id,
  'territory_claim',
  aa.id::text,
  200,
  aa.created_at,
  jsonb_build_object(
    'activityId', aa.id,
    'metadata', COALESCE(aa.metadata, '{}'::jsonb)
  )
FROM public.alliance_activity aa
WHERE aa.event_type = 'territory_claimed'
ON CONFLICT (alliance_id, source_type, source_key) DO NOTHING;

-- Rebuild every current alliance after backfill.
DO $block$
DECLARE
  v_alliance record;
BEGIN
  FOR v_alliance IN
    SELECT a.id
      FROM public.alliances a
     ORDER BY a.id
  LOOP
    PERFORM public.nexora_rebuild_alliance_progression(v_alliance.id);
  END LOOP;
END;
$block$;

