  level integer NOT NULL
    REFERENCES public.game_alliance_levels(level) ON DELETE RESTRICT,
  configured_reward jsonb NOT NULL DEFAULT '{}'::jsonb
    CHECK (jsonb_typeof(configured_reward) = 'object'),
  reward jsonb NOT NULL DEFAULT '{}'::jsonb
    CHECK (jsonb_typeof(reward) = 'object'),
  claimed_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  PRIMARY KEY (player_id, alliance_id, level)
);

CREATE INDEX IF NOT EXISTS idx_alliance_level_reward_claims_alliance_level
  ON public.player_alliance_level_reward_claims(
    alliance_id,
    level,
    claimed_at
  );

