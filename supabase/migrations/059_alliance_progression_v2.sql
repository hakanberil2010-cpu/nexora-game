-- NEXORA - Alliance Progression V2
-- Migration 059
--
-- Adds durable alliance XP, levels and milestone rewards without changing
-- existing alliance membership, wars, territories or weekly mission behavior.
--
-- XP sources (server-authoritative and non-spammable):
-- - First weekly Alliance Mission chest claim for an alliance/week: +250 XP
-- - Each won Alliance War battle/round: +40 XP
-- - Each finished Alliance War victory: +150 XP
-- - Each territory_claimed alliance activity event: +200 XP
--
-- Level thresholds:
-- 1: 0
-- 2: 100
-- 3: 250
-- 4: 500
-- 5: 900
-- 6: 1400
-- 7: 2000
-- 8: 2800
-- 9: 3800
-- 10: 5000
--
-- Milestone rewards are claimable once per eligible member and level.
-- A member is eligible only if their current membership joined_at is at or
-- before the milestone reached_at timestamp. This prevents joining a mature
-- alliance solely to collect historical level rewards.
--
-- Apply after 058_boss_rewards_trophy_history_v2.sql.
-- Backend/frontend integration is intentionally NOT part of this migration.

BEGIN;

