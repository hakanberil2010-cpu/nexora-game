CREATE OR REPLACE FUNCTION public.nexora_track_alliance_war_win_xp()
RETURNS trigger
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public, pg_temp
AS $function$
BEGIN
  IF NEW.status = 'finished'
     AND NEW.winner_alliance_id IS NOT NULL
     AND (
       TG_OP = 'INSERT'
       OR OLD.status IS DISTINCT FROM NEW.status
       OR OLD.winner_alliance_id IS DISTINCT FROM NEW.winner_alliance_id
     ) THEN
    PERFORM public.nexora_add_alliance_xp_event(
      NEW.winner_alliance_id,
      'war_win',
      NEW.id::text,
      150,
      COALESCE(
        NEW.finished_at,
        NEW.ends_at,
        NEW.started_at,
        NEW.created_at
      ),
      jsonb_build_object(
        'warId', NEW.id,
        'challengerScore', NEW.challenger_score,
        'targetScore', NEW.target_score
      )
    );
  END IF;
  RETURN NEW;
END;
$function$;

